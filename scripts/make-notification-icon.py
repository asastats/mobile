"""Write the Android notification (status bar) icon from the logo.

Run from the repository root: python3 scripts/make-notification-icon.py
(standard library only). Source: assets/logo.svg, the two-line wordmark.
Output: android/app/src/main/res/drawable/ic_stat_asastats.xml, a white
silhouette Android tints itself. See docs/logbook.md.
"""

import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/logo.svg"
TARGET = ROOT / "android/app/src/main/res/drawable/ic_stat_asastats.xml"

SVG = "{http://www.w3.org/2000/svg}"
#: The glyph fits the central 20 dp of the 24 dp icon (Android's keyline).
SAFE = 20 / 24

MATRIX = re.compile(r"matrix\(([^)]*)\)")
TOKENS = re.compile(r"[A-Za-z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def path_points(data):
    """Return every point of an SVG path made of m/l/h/v (either case) and z.

    :param data: the `d` attribute
    :return: list of (x, y)
    """
    tokens = TOKENS.findall(data)
    points, x, y, start, command, i = [], 0.0, 0.0, (0.0, 0.0), None, 0
    while i < len(tokens):
        if tokens[i].isalpha():
            command = tokens[i]
            i += 1
            if command in "zZ":
                x, y = start
                continue
        relative = command.islower()
        kind = command.lower()
        if kind in "ml":
            dx, dy = float(tokens[i]), float(tokens[i + 1])
            i += 2
            x, y = (x + dx, y + dy) if relative else (dx, dy)
            if kind == "m":
                start = (x, y)
                # Further pairs after a moveto are linetos.
                command = "l" if relative else "L"
        elif kind == "h":
            value = float(tokens[i])
            i += 1
            x = x + value if relative else value
        elif kind == "v":
            value = float(tokens[i])
            i += 1
            y = y + value if relative else value
        else:
            raise ValueError(f"unsupported path command {command!r}: extend path_points")
        points.append((x, y))
    return points


def groups(root):
    """Yield (scale, tx, ty, [path data]) for each coloured group of the logo.

    :param root: the parsed SVG
    """
    for group in root.iter(f"{SVG}g"):
        paths = [p.get("d") for p in group.findall(f"{SVG}path")]
        if not paths:
            continue
        a, b, c, d, e, f = (float(v) for v in re.split(r"[ ,]+", MATRIX.search(group.get("transform")).group(1).strip()))
        if b or c or a != d:
            raise ValueError("only uniform scale + translate transforms are supported")
        yield a, e, f, paths


def main():
    """Write the vector drawable."""
    root = ET.parse(SOURCE).getroot()
    found = list(groups(root))
    xs, ys = [], []
    for scale, tx, ty, paths in found:
        for data in paths:
            for x, y in path_points(data):
                xs.append(x * scale + tx)
                ys.append(y * scale + ty)
    left, top, width, height = min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)
    viewport = max(width, height) / SAFE
    offset_x = (viewport - width) / 2 - left
    offset_y = (viewport - height) / 2 - top

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/make-notification-icon.py from assets/logo.svg; do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        f'    android:viewportWidth="{viewport:.4f}"',
        f'    android:viewportHeight="{viewport:.4f}">',
        f'    <group android:translateX="{offset_x:.4f}" android:translateY="{offset_y:.4f}">',
    ]
    for scale, tx, ty, paths in found:
        lines.append(
            f'        <group android:scaleX="{scale}" android:scaleY="{scale}"'
            f' android:translateX="{tx}" android:translateY="{ty}">'
        )
        for data in paths:
            lines.append(f'            <path android:fillColor="#FFFFFFFF" android:pathData="{data}" />')
        lines.append("        </group>")
    lines += ["    </group>", "</vector>", ""]
    TARGET.write_text("\n".join(lines))
    print(f"{TARGET.relative_to(ROOT)}: {len(xs)} points, glyph {width:.1f} x {height:.1f}, viewport {viewport:.1f}")


if __name__ == "__main__":
    main()
